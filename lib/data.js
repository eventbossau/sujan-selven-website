export function newsBySlug(slug) {
  return news.find((n) => n.slug === slug) || null;
}

export function newsForPriority(pkey) {
  const p = priorities.find((x) => x.key === pkey);
  if (!p?.newsSlugs) return news.slice(0, 3);
  return p.newsSlugs.map((s) => newsBySlug(s)).filter(Boolean);
}
